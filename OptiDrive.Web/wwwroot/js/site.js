    const translatedValues = new Set(Object.values(translations));
    let activeLanguage = localStorage.getItem("optidrive-language") || "pt";
    let isTranslating = false;

    function translateValue(original, language) {
        const trimmed = original.trim();
        if (!trimmed) {
            return original;
        }

        let translated = trimmed;
        if (language === "en") {
            translated = translations[trimmed] || translateWithRegex(trimmed) || trimmed;
        }

        if (!translated || (language === "en" && translated === trimmed && !translations[trimmed])) {
            return original;
        }

        return original.replace(trimmed, translated);
    }

    function translateWithRegex(value) {
        for (const [pattern, replacement] of regexTranslations) {
            if (pattern.test(value)) {
                return value.replace(pattern, replacement);
            }
        }

        return null;
    }

    function translateTextNode(node, language) {
        if (!node.parentElement || ["SCRIPT", "STYLE", "NOSCRIPT"].includes(node.parentElement.tagName)) {
            return;
        }

        if (!node.__optidriveOriginalText) {
            const trimmed = node.textContent.trim();
            if (!trimmed || translatedValues.has(trimmed)) {
                return;
            }
            node.__optidriveOriginalText = node.textContent;
        }

        node.textContent = translateValue(node.__optidriveOriginalText, language);
    }

    function translateAttributes(element, language) {
        ["placeholder", "title", "aria-label"].forEach((attribute) => {
            if (!element.hasAttribute(attribute)) {
                return;
            }

            const originalKey = `i18n${attribute.replace("-", "")}Original`;
            if (!element.dataset[originalKey]) {
                const current = element.getAttribute(attribute) || "";
                if (!current.trim() || translatedValues.has(current.trim())) {
                    return;
                }
                element.dataset[originalKey] = current;
            }

            element.setAttribute(attribute, translateValue(element.dataset[originalKey], language));
        });
    }

    function applyLanguage(language, root = document.body) {
        if (!root || isTranslating) {
            return;
        }

        isTranslating = true;
        activeLanguage = language === "en" ? "en" : "pt";
        localStorage.setItem("optidrive-language", activeLanguage);
        document.documentElement.lang = activeLanguage === "en" ? "en" : "pt-PT";
        if (!document.documentElement.dataset.originalTitle) {
            document.documentElement.dataset.originalTitle = document.title;
        }
        document.title = translateValue(document.documentElement.dataset.originalTitle, activeLanguage);

        const textRoot = root.nodeType === Node.TEXT_NODE ? root.parentElement : root;
        if (root.nodeType === Node.TEXT_NODE) {
            translateTextNode(root, activeLanguage);
        } else {
            const walker = document.createTreeWalker(textRoot, NodeFilter.SHOW_TEXT);
            while (walker.nextNode()) {
                translateTextNode(walker.currentNode, activeLanguage);
            }
        }

        const elementRoot = root.nodeType === Node.ELEMENT_NODE ? root : root.parentElement;
        if (elementRoot) {
            const elements = [elementRoot, ...elementRoot.querySelectorAll("[placeholder], [title], [aria-label]")];
            elements.forEach((element) => translateAttributes(element, activeLanguage));
        }

        document.querySelectorAll("[data-language-option]").forEach((button) => {
            const isActive = button.dataset.languageOption === activeLanguage;
            button.classList.toggle("is-active", isActive);
            button.setAttribute("aria-pressed", String(isActive));
        });
        updateThemeLabel();
        isTranslating = false;
    }

    function updateThemeLabel() {
        const label = document.querySelector("[data-theme-label]");
        const isDark = document.documentElement.dataset.theme === "dark";
        document.querySelector("[data-theme-toggle]")?.setAttribute("aria-pressed", String(isDark));
        if (!label) {
            return;
        }

        const text = isDark ? "Modo claro" : "Modo escuro";
        const nextText = activeLanguage === "en" ? translations[text] : text;
        if (label.textContent !== nextText) {
            label.textContent = nextText;
        }
    }

    function applyTheme(theme) {
        const normalized = theme === "dark" ? "dark" : "light";
        document.documentElement.dataset.theme = normalized;
        localStorage.setItem("optidrive-theme", normalized);
        updateThemeLabel();
    }

    window.OptiDrivePreferences = {
        applyLanguage,
        applyTheme
    };

    document.addEventListener("DOMContentLoaded", () => {
        applyTheme(localStorage.getItem("optidrive-theme") || "light");
        applyLanguage(activeLanguage);

        document.querySelector("[data-theme-toggle]")?.addEventListener("click", () => {
            applyTheme(document.documentElement.dataset.theme === "dark" ? "light" : "dark");
        });

        document.querySelectorAll("[data-language-option]").forEach((button) => {
            button.addEventListener("click", () => applyLanguage(button.dataset.languageOption));
        });

        let pendingDynamicTranslation = false;
        const observer = new MutationObserver((mutations) => {
            if (isTranslating || activeLanguage !== "en") {
                return;
            }

            if (!mutations.some((mutation) => mutation.addedNodes.length > 0) || pendingDynamicTranslation) {
                return;
            }

            pendingDynamicTranslation = true;
            window.requestAnimationFrame(() => {
                pendingDynamicTranslation = false;
                applyLanguage(activeLanguage);
            });
        });
        observer.observe(document.body, { childList: true, subtree: true });
    });
